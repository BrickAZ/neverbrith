local core = dofile('scripts/features/musicbox/core.lua')
assert(core.Duration == 600 and core.PlanCDelay == 90)
assert(core.MatchesRun({ runSeed = 'a' }, 'a'))
assert(not core.MatchesRun(nil, 'a') and not core.MatchesRun({ runSeed = 'b' }, 'a'))
assert(core.NextTimer(600, true) == 599)
assert(core.NextTimer(1, true) == 0)
assert(core.NextTimer(0, true) == 0)
assert(core.NextTimer(30, false) == 30, 'missing player must not advance debt')
assert(core.NextTimer('5', true) == 4)
assert(core.GetVisualKind(151,150,60) == 'Contract')
assert(core.GetVisualKind(150,150,60) == 'Windup')
assert(core.GetVisualKind(61,150,60) == 'Windup')
assert(core.GetVisualKind(60,150,60) == 'Beat')
assert(core.GetVisualKind(0,150,60) == 'Beat')
print('musicbox core tests passed: run matching, single tick, visual boundaries')
