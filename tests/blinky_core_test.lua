local Core = assert(loadfile('blinky_core.lua'))()
local function eq(a,b,m) assert(a==b,(m or '')..' expected '..tostring(b)..', got '..tostring(a)) end
local state=Core.Ensure({},'run1')
eq(Core.Damage('melee',10),2)
eq(Core.Damage('rock',10),7)
eq(Core.Damage('poop',10),5)
eq(Core.Damage('dip',10),2.5)
eq(Core.Damage('chest',10),20)
eq(Core.Damage('tnt',10),40)
eq(Core.InCone({X=0,Y=0},{X=1,Y=0},{X=90,Y=20},100),true)
eq(Core.InCone({X=0,Y=0},{X=1,Y=0},{X=90,Y=30},100),false,'total 30 degrees')
eq(Core.InCone({X=0,Y=0},{X=1,Y=0},{X=-1,Y=0},100),false)
eq(Core.InCone({X=0,Y=0},{X=1,Y=0},{X=101,Y=0},100),false)
local e={kind='pickup',variant=100,subtype=25,price=-2,charge=3,seed=42,state=0}
local a=Core.Add(state,'a',e,{room='r1',token='p:42'})
local b=Core.Add(state,'a',e,{room='r1',token='p:43'})
eq(a==b,false,'distinct pickup instances')
e.price=0;eq(Core.Find(state,'a',a).price,-2,'snapshot does not alias world')
eq(#Core.Entries(state,'b'),0,'owner isolated')
eq(Core.IsConsumed(state,'r1','p:42'),true)
eq(Core.IsConsumed(state,'r2','p:42'),false,'room identity')
eq(Core.Take(state,'a',a,function() return false end),false)
eq(#Core.Entries(state,'a'),2,'failed spawn preserves inventory')
local saved
eq(Core.Take(state,'a',a,function(entry) saved=entry return true end),true)
eq(#Core.Entries(state,'a'),1)
eq(Core.Return(state,'a',saved),true,'interrupted flight restores once')
eq(Core.Return(state,'a',saved),false)
eq(Core.Find(state,'a',a).charge,3)
eq(Core.Ensure({blinky=state},'run1'),state,'continue keeps non-hourglass state')
eq(#Core.Entries(Core.Ensure({blinky=state},'run2'),'a'),0,'new run resets')
for i=1,1200 do Core.Add(state,'a',{kind='rock'}) end
eq(#Core.Entries(state,'a'),1202,'no gameplay capacity cap')
eq(Core.Reward(state,'a','death1'),true)
eq(Core.Reward(state,'a','death1'),false,'one death one heart')
eq(Core.Entries(state,'a')[1203].kind,'pickup')
eq(Core.Entries(state,'a')[1203].subtype,1)
print('blinky_core_test: geometry, damage, instance storage, transaction, persistence, capacity and rewards passed')
