-- Explicit, temporary native test. Loaded only by the isolated runner.
return function(mod,options)
    local phase,tick,boot='menu',0,0
    local game=Game();local index,passed,failed=0,0,0
    local current,prepareAt,finishedAt
    local cases={
        {key='wave',name='Wave',zh='波动',frames=66,version='v7',directions={}},
        {key='dp',name='Dragon Punch',zh='升龙',frames=78,version='v7',directions={{1},{3},{1,3}}},
        {key='circle_360',name='360',frames=108,version='v7',directions={{1},{3},{0},{2}}},
        {key='circle_720',name='720',frames=394,version='v9',directions={{1},{3},{0},{2},{1},{3},{0},{2}}},
    }
    if options.ExitDuringPlayback then cases={cases[4]}end
    local function log(s)
        Isaac.DebugString('[Motion runtime probe] '..s)
    end
    local function check(name,condition,detail)
        if condition then passed=passed+1 else failed=failed+1 end
        log((condition and 'PASS ' or 'FAIL ')..current.key..' '..name..' '..tostring(detail or ''))
    end
    local values={}
    local nativeValue=Input.GetActionValue
    -- Feed the Lua raw-input boundary, too: Input.GetActionValue bypasses the
    -- engine's MC_INPUT_ACTION hook. No OS input is generated by this probe.
    Input.GetActionValue=function(action,controller)
        if phase=='running' then return values[action] or 0 end
        return nativeValue(action,controller)
    end
    mod:AddPriorityCallback(ModCallbacks.MC_INPUT_ACTION,-9999999,function(_,entity,hook,action)
        if phase~='running' and phase~='exit_pending' then return end
        return hook==InputHook.GET_ACTION_VALUE and 0 or false
    end)
    mod:AddCallback(ModCallbacks.MC_PRE_RENDER,function()
        if phase~='menu' then return end
        boot=boot+1;if boot<5 then return end
        phase='starting';log('START attempt='..options.Attempt..' version='..REPENTOGON.Version)
        Isaac.StartNewGame(0,0,0,31415926)
    end)
    mod:AddPriorityCallback(ModCallbacks.MC_POST_GAME_STARTED,9999999,function()
        phase='running';tick=0;prepareAt=game:GetFrameCount()+20
        local count=0;for _ in pairs(mod.MotionInput.bindings)do count=count+1 end
        log('LOADED bindings='..count)
    end)
    local function start(p)
        if current and current.id then p:RemoveCollectible(current.id)end
        index=index+1;current=cases[index]
        if not current then
            phase='done';Input.GetActionValue=nativeValue
            log('SUMMARY checks='..passed..' passed fail='..failed..' cases='..(index-1))
            for _=1,10 do log('DONE '..string.rep('.',1024))end
            return
        end
        local id=Isaac.GetItemIdByName(current.name)
        if id<0 and current.zh then id=Isaac.GetItemIdByName(current.zh)end
        current.id=id;current.start=game:GetFrameCount();current.renders=0;current.executions=0;current.maxFrame=-1
        p:AddCollectible(id);finishedAt=nil
        check('native-ownership',p:HasCollectible(id)and p:GetActiveItem(0)==id,id)
        check('no-arm-needed',not next(mod.MotionInput.rehearsals))
    end
    mod:AddPriorityCallback(ModCallbacks.MC_PRE_PLAYER_UPDATE,-9999999,function(_,p)
        if phase~='running' then return end
        local now=game:GetFrameCount();values={}
        if prepareAt and now>=prepareAt then prepareAt=nil;start(p)end
        if phase~='running' or not current or finishedAt then return end
        local t=now-current.start
        if t>=1 and t<=3 then values[ButtonAction.ACTION_SHOOTRIGHT]=1 end
        if t>=5 and t<40 then values[ButtonAction.ACTION_ITEM]=1 end
        if current.key=='wave' then
            if t>=8 and t<=12 then values[ButtonAction.ACTION_SHOOTRIGHT]=1 end
        else
            local step=math.floor((t-8)/2)+1
            if step>=1 and step<=#current.directions then
                for _,action in ipairs(current.directions[step])do values[action+4]=1 end
            end
        end
    end)
    mod:AddPriorityCallback(ModCallbacks.MC_POST_RENDER,9999999,function()
        if phase~='running' or not current then return end
        local state=mod.MotionPresentation:GetState(Isaac.GetPlayer(0))
        if state and not current.renderContext then
            current.renderContext=true
            log('RENDER_CONTEXT '..current.key..' mode='..game:GetRoom():GetRenderMode()..' null='..RenderMode.RENDER_NULL)
        end
        if state and state.renderedFrame==state.frame then
            current.renders=current.renders+1;current.maxFrame=math.max(current.maxFrame,state.frame)
            current.cinema=current.cinema or state.cinema
        end
    end)
    mod:AddPriorityCallback(ModCallbacks.MC_POST_UPDATE,9999999,function()
        if phase=='exit_pending' then
            -- Keep the owned cinematic live until the runner closes the app,
            -- even when the engine buffers its diagnostic output until exit.
            for _,session in pairs(mod.MotionPresentation.states)do
                session.frame=50;session.advanced=game:GetFrameCount()
            end
            return
        end
        if phase~='running' or not current then return end
        local p=Isaac.GetPlayer(0);local now=game:GetFrameCount()
        local state=mod.MotionPresentation:GetState(p);local input=mod.MotionInput:GetState(p)
        local event=input.lastEvent
        if event and event.kind=='execute' and event.serial~=current.serial then
            current.serial=event.serial;current.executions=current.executions+1
        end
        if state and not current.played then
            current.played=true
            log('PLAY '..state.key..' source='..state.version..' length='..state.frames..' owner='..tostring(state.sourceOwner))
            check('formal-playback',state.key==current.key and state.presentationOnly and not state.rehearsal)
            check('approved-version',state.version==current.version,state.version)
            check('locked-facing',state.facing=='right',state.facing)
            local clean=true
            for _,session in pairs(mod.MotionPresentation.states)do
                for _,layer in ipairs(session.sprite:GetAllLayers())do
                    if layer:GetName():find('target_',1,true)or layer:GetSpritesheetPath():find('target_',1,true)then clean=false end
                end
            end
            check('no-demo-opponent-resource',clean)
        end
        if options.ExitDuringPlayback and state and state.frame>=50 then
            check('exit-with-live-V9',state.cinema==true and state.version=='v9',state.frame)
            phase='exit_pending';Input.GetActionValue=nativeValue
            log('SUMMARY checks='..passed..' passed fail='..failed..' cases=1 exitDuringPlayback=true')
            for _=1,128 do log('DONE '..string.rep('.',1024))end
            return
        end
        if current.played and not state and not finishedAt then finishedAt=now end
        if now-current.start>current.frames+60 and not finishedAt then
            check('starts-and-finishes',false,event and (event.kind..':'..tostring(event.reason)) or 'no event')
            finishedAt=now
        end
        if finishedAt and now>=finishedAt+5 and not prepareAt then
            check('rendered-to-end',current.renders>0 and current.maxFrame>=current.frames-2,'renders='..current.renders..' max='..current.maxFrame)
            check('single-execution',current.executions==1,current.executions)
            if current.key=='circle_720' then check('V9-cinematic',current.cinema==true)end
            check('native-player-visible',p.Visible)
            prepareAt=now+1
        end
    end)
    mod:AddPriorityCallback(ModCallbacks.MC_PRE_GAME_EXIT,-99999999,function()
        for _,session in pairs(mod.MotionPresentation.states)do
            log('EXIT_PLAYBACK key='..session.key..' frame='..session.frame..' rendered='..tostring(session.renderedFrame))
        end
    end)
end
